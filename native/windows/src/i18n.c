void i18n_set(const char *lang) { g_en = lang && (lang[0] == 'e' || lang[0] == 'E') && (lang[1] == 'n' || lang[1] == 'N'); }

int i18n_en(void) { return g_en; }

const wchar_t *i18n(const char *key) {
  if (!key || !key[0]) return L"";
  int n = (int)(sizeof kTab / sizeof kTab[0]);
  for (int i = 0; i < n; i++) {
    if (strcmp(kTab[i].id, key) == 0) return g_en ? kTab[i].en : kTab[i].ru;
  }
  return L"";
}

const char *i18n_u(const char *key) {
  static char buf[2][384];
  static int bi;
  bi ^= 1;
  wide_to_utf8(i18n(key), buf[bi], (int)sizeof buf[bi]);
  return buf[bi];
}

